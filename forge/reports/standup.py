"""Render a ProjectSummary as a standup in Markdown.

The layout follows the standup skill (done / now / blockers) but every line
is filled from a record and carries that record's ID, so a reader can check
it. Nothing here is generated by a model.

Titles, reasons and questions are user- or model-supplied text. They are
escaped so they cannot inject Markdown links, images, headings or tables
into the report, and flattened to one line so they cannot break the layout.
"""

from __future__ import annotations

import re

from forge.reports.summary import ProjectSummary, Section

# Characters that change meaning anywhere in a line: emphasis, code, links,
# images, tables. "-", "+" and "." only matter at the start of a line, and
# escaped text is never placed at the start of a line here.
_MARKDOWN_SPECIAL = re.compile(r"([\\`*_{}\[\]()#!|~])")
_WHITESPACE = re.compile(r"\s+")
MAX_TEXT = 160


def escape(text: str, limit: int = MAX_TEXT) -> str:
    """One line of untrusted text, safe to place inside Markdown.

    HTML characters become entities rather than backslash escapes: a
    backslash only neutralizes "<" in renderers that follow CommonMark, while
    "&lt;" is shown as a literal "<" by every Markdown or HTML renderer.
    """
    flat = _WHITESPACE.sub(" ", text).strip()
    if len(flat) > limit:
        flat = flat[: limit - 1] + "…"
    flat = flat.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return _MARKDOWN_SPECIAL.sub(r"\\\1", flat)


def _more(section: Section) -> list[str]:
    return [f"- …and {section.hidden} more"] if section.hidden else []


def render_standup(summary: ProjectSummary) -> str:
    window = (
        "since the project started"
        if summary.since_event_seq == 0
        else f"since event #{summary.since_event_seq}"
    )
    lines = [
        f"## Standup: {escape(summary.name)}",
        "",
        f"As of event #{summary.as_of_event_seq}, {window}. "
        f"Evaluated {summary.evaluated_at}.",
        "",
        "### Done",
    ]
    if summary.done.total == 0:
        lines.append("- Nothing completed in this window.")
    for item in summary.done.items:
        lines.append(f"- {escape(item.title)} (`{item.task_id}`), event #{item.event_seq}")
    lines += _more(summary.done)

    if summary.ended.total:
        lines += ["", "### Ended without completing"]
        for item in summary.ended.items:
            lines.append(
                f"- {escape(item.title)} (`{item.task_id}`) {item.status}: {escape(item.reason)}"
            )
        lines += _more(summary.ended)

    lines += ["", "### Now"]
    if summary.running.total == 0 and summary.ready.total == 0:
        lines.append("- Nothing running and nothing ready to start.")
    for item in summary.running.items:
        lines.append(f"- Running: {escape(item.title)} (`{item.task_id}`)")
    lines += _more(summary.running)
    for item in summary.ready.items:
        lines.append(f"- Ready: {escape(item.title)} (`{item.task_id}`, {item.task_type})")
    lines += _more(summary.ready)

    lines += ["", "### Blockers"]
    blocker_total = (
        summary.blocked.total
        + summary.waiting_for_user.total
        + summary.waiting_on_tasks.total
        + summary.pending_decisions.total
    )
    if blocker_total == 0:
        lines.append("- None.")
    for item in summary.blocked.items:
        lines.append(
            f"- Blocked: {escape(item.title)} (`{item.task_id}`): {escape(item.reason)} "
            f"(since event #{item.event_seq})"
        )
    lines += _more(summary.blocked)
    for item in summary.waiting_for_user.items:
        lines.append(
            f"- Waiting for you: {escape(item.title)} (`{item.task_id}`): {escape(item.reason)}"
        )
    lines += _more(summary.waiting_for_user)
    for item in summary.waiting_on_tasks.items:
        count = len(item.waiting_on)
        noun = "task" if count == 1 else "tasks"
        lines.append(
            f"- Waiting on {count} unfinished {noun}: {escape(item.title)} (`{item.task_id}`)"
        )
    lines += _more(summary.waiting_on_tasks)
    for item in summary.pending_decisions.items:
        expiry = ""
        if item.expired:
            expiry = f" EXPIRED at {item.expires_at}; it can no longer be recorded"
        elif item.expires_at:
            expiry = f" (expires {item.expires_at})"
        lines.append(f"- Decision needed: {escape(item.question)} (`{item.decision_id}`){expiry}")
    lines += _more(summary.pending_decisions)

    if summary.decided.total:
        lines += ["", "### Decided"]
        for item in summary.decided.items:
            lines.append(
                f"- {item.disposition}: {escape(item.question)} (`{item.decision_id}`): "
                f"{escape(item.reason)}"
            )
        lines += _more(summary.decided)

    counts = ", ".join(f"{status} {count}" for status, count in summary.status_counts.items())
    lines += ["", f"Task counts: {counts}."]
    return "\n".join(lines) + "\n"
