"""NASA/JPL "Power of Ten" rules for safety-critical C, as a deterministic FORGE analyzer.

Source: G. J. Holzmann, "The Power of Ten: Rules for Developing
Safety-Critical Code", IEEE Computer, June 2006. The rules below are FORGE's
own short paraphrases; the paper's text is not reproduced.

What is checked here, from the source text alone (comments and string
literals removed; nothing is compiled or run):

  P10-1  no goto, setjmp or longjmp, and no direct or indirect recursion among
         the functions in the analyzed files                       [decidable]
  P10-2  every loop has a fixed upper bound: `for (;;)`, `while (1)` and
         `while (true)` are reported; proving bounds in general needs a
         person                                                    [person]
  P10-3  no dynamic allocation after initialization: allocation calls outside
         functions named *init* are reported for a person to confirm [person]
  P10-4  no function longer than 60 lines                         [decidable]
  P10-5  at least two assertions per function on average, per file [decidable]
  P10-6  data at the smallest possible scope                       [person]
  P10-7  check return values: enforced by the CERT ERR33-C checks in the same
         profile, not repeated here
  P10-8  preprocessor limited to includes and simple macros: token pasting
         (##) and variadic macros are reported                     [decidable]
  P10-9  at most one level of pointer dereference and no function pointers:
         pointer-to-pointer declarations (except main's argv), function-pointer
         declarators and pointer typedefs are reported             [decidable]
  P10-10 compile with all warnings and zero warnings: enforced by the
         compiler and analyzer runs in the same profile

Limits: this is a careful lexical analysis, not a C front end. Macros are not
expanded, so a rule broken inside a macro body is reported at the macro, and
code generated by macros is not seen.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from forge.quality.findings import QualityFinding

C_SUFFIXES = (".c", ".h")
MAX_FUNCTION_LINES = 60
MIN_ASSERTIONS_PER_FUNCTION = 2.0
_KEYWORDS = {"if", "while", "for", "switch", "return", "sizeof", "_Alignof", "alignof", "defined", "do", "else",
             "case", "goto", "typeof", "__typeof__", "_Generic", "_Static_assert", "static_assert"}
_ALLOCATORS = {"malloc", "calloc", "realloc", "free", "aligned_alloc", "strdup", "strndup", "alloca"}
_IDENT = re.compile(r"[A-Za-z_]\w*")
RULES = {
    "P10-1": "no goto, setjmp/longjmp or recursion", "P10-2": "every loop has a fixed upper bound",
    "P10-3": "no dynamic memory allocation after initialization", "P10-4": "functions of at most 60 lines",
    "P10-5": "at least two assertions per function on average", "P10-6": "data declared at the smallest scope",
    "P10-8": "preprocessor limited to includes and simple macros",
    "P10-9": "one level of pointer dereference, no function pointers",
}


def strip(text: str) -> str:
    """Blank out comments and string/character literals, keeping every newline (so line numbers stay right)."""
    out, i, n = [], 0, len(text)
    while i < n:
        two = text[i:i + 2]
        if two == "/*":
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            out.append(re.sub(r"[^\n]", " ", text[i:end]))
            i = end
        elif two == "//":
            end = text.find("\n", i)
            end = n if end < 0 else end
            out.append(" " * (end - i))
            i = end
        elif text[i] in "\"'":
            quote, j = text[i], i + 1
            while j < n and text[j] != quote and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            j = min(n, j + 1)
            out.append(quote + re.sub(r"[^\n]", " ", text[i + 1:j - 1]) + (quote if j - 1 > i else ""))
            i = j
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


@dataclass
class Function:
    name: str
    path: str
    start: int            # line of the opening brace
    end: int              # line of the closing brace
    calls: list[tuple[str, int]] = field(default_factory=list)
    assertions: int = 0
    gotos: list[int] = field(default_factory=list)
    endless: list[int] = field(default_factory=list)


def _line(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def functions(path: str, code: str) -> list[Function]:
    """Function definitions at file scope: `name ( ... ) {` with a matching brace."""
    found, depth, i = [], 0, 0
    while i < len(code):
        ch = code[i]
        if ch == "{":
            if depth == 0:
                head = code[:i].rstrip()
                if head.endswith(")"):
                    level, j = 0, len(head) - 1
                    while j >= 0:
                        level += {")": 1, "(": -1}.get(head[j], 0)
                        if level == 0:
                            break
                        j -= 1
                    name = re.search(r"([A-Za-z_]\w*)\s*$", head[:j])
                    if name and name.group(1) not in _KEYWORDS:
                        close, level = i, 0
                        while close < len(code):
                            level += {"{": 1, "}": -1}.get(code[close], 0)
                            if level == 0:
                                break
                            close += 1
                        body = code[i:close + 1]
                        function = Function(name.group(1), path, _line(code, i), _line(code, close))
                        for match in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", body):
                            callee = match.group(1)
                            if callee not in _KEYWORDS:
                                function.calls.append((callee, _line(code, i + match.start())))
                            if callee == "assert" or callee.endswith(("_assert", "ASSERT")):
                                function.assertions += 1
                        function.gotos = [_line(code, i + m.start()) for m in re.finditer(r"\bgoto\b", body)]
                        function.endless = [_line(code, i + m.start()) for m in re.finditer(
                            r"\bfor\s*\(\s*;\s*;\s*\)|\bwhile\s*\(\s*(?:1|true)\s*\)", body)]
                        found.append(function)
                        i = close + 1
                        continue
            depth += 1
        elif ch == "}":
            depth = max(0, depth - 1)
        i += 1
    return found


def _recursive(all_functions: list[Function]) -> set[str]:
    """Names of functions on a call cycle (direct or indirect), among the analyzed definitions."""
    graph = {f.name: {callee for callee, _ in f.calls} for f in all_functions}
    names = set(graph)
    on_cycle: set[str] = set()
    for start in sorted(names):
        stack, seen = [iter(sorted(graph[start] & names))], {start}
        path = [start]
        while stack:
            nxt = next(stack[-1], None)
            if nxt is None:
                stack.pop()
                path.pop()
                continue
            if nxt == start:
                on_cycle.update(path)
            elif nxt not in seen:
                seen.add(nxt)
                path.append(nxt)
                stack.append(iter(sorted(graph[nxt] & names)))
    return on_cycle


def analyze(files: dict[str, bytes]) -> list[QualityFinding]:
    findings: list[QualityFinding] = []

    def report(rule: str, path: str, line: int, message: str, *, decidable: bool = True) -> None:
        findings.append(QualityFinding(
            tool="power-of-ten", rule_id=rule, level="error" if decidable else "warning",
            message=f"{message} (Power of Ten {rule}: {RULES[rule]})", path=path, line=line,
            standards=[f"Power of Ten {rule}"], severity="high" if decidable else "medium", blocking=decidable,
            decidable=decidable))

    every: list[Function] = []
    for path in sorted(p for p in files if p.lower().endswith(C_SUFFIXES)):
        code = strip(files[path].decode("utf-8", "replace"))
        defined = functions(path, code)
        every.extend(defined)
        for function in defined:
            for line in function.gotos:
                report("P10-1", path, line, f"goto in {function.name}")
            for callee, line in function.calls:
                if callee in ("setjmp", "longjmp", "_setjmp", "sigsetjmp", "siglongjmp"):
                    report("P10-1", path, line, f"{callee} in {function.name}")
                if callee in _ALLOCATORS and "init" not in function.name.lower():
                    report("P10-3", path, line, f"{callee} in {function.name}: confirm it runs only during "
                           "initialization", decidable=False)
            for line in function.endless:
                report("P10-2", path, line, f"loop without a bound in {function.name}: confirm it is meant to "
                       "run forever (for example a scheduler) or give it a fixed bound", decidable=False)
            length = function.end - function.start + 1
            if length > MAX_FUNCTION_LINES:
                report("P10-4", path, function.start, f"{function.name} is {length} lines long "
                       f"(at most {MAX_FUNCTION_LINES})")
        if defined:
            average = sum(f.assertions for f in defined) / len(defined)
            if average < MIN_ASSERTIONS_PER_FUNCTION:
                report("P10-5", path, defined[0].start, f"{average:.1f} assertions per function in this file "
                       f"(at least {MIN_ASSERTIONS_PER_FUNCTION:.0f} on average)")
        for number, line in enumerate(code.splitlines(), 1):
            stripped = line.strip()
            if stripped.startswith("#") and re.match(r"#\s*define\b", stripped):
                if "##" in stripped:
                    report("P10-8", path, number, "token pasting (##) in a macro")
                if re.search(r"\(\s*[^)]*\.\.\.\s*\)", stripped):
                    report("P10-8", path, number, "variadic macro")
                continue
            if re.search(r"\(\s*\*\s*[A-Za-z_]\w*\s*\)\s*\(", line):
                report("P10-9", path, number, "function pointer")
            if re.match(r"\s*typedef\b[^;]*\*", line):
                report("P10-9", path, number, "pointer hidden in a typedef")
            for match in re.finditer(r"\*\s*\*+\s*(?:const\s+)?([A-Za-z_]\w*)", line):
                before = line[:match.start()].rstrip()
                declaration = re.search(r"(?:\b(?:char|int|short|long|float|double|void|unsigned|signed|bool|"
                                        r"const|struct\s+\w+|[A-Za-z_]\w*_t)|[,(])\s*$", before)
                if declaration and not (match.group(1) == "argv" and "main" in line):
                    report("P10-9", path, number, f"pointer to pointer: {match.group(1)}")
    for name in sorted(_recursive(every)):
        function = next(f for f in every if f.name == name)
        report("P10-1", function.path, function.start, f"{name} is recursive (directly or through other calls)")
    return findings


def attestations() -> list[str]:
    """Rules no tool can decide here: each needs a person's statement in the compliance record."""
    return ["P10-2: every loop has a provable fixed upper bound", "P10-3: no allocation after initialization",
            "P10-6: data objects are declared at the smallest possible scope"]
